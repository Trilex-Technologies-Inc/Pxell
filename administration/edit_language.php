if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    $submittedToken = (string) ($_POST['csrf_token'] ?? '');
    if (!hash_equals($csrfToken, $submittedToken)) {
        $errorMessage = 'The form expired or is invalid. Reload the page and try again.';
    } else {
        $action = $_POST['action'] ?? '';
        $translations = language_editor_load($sellang);

        if ($action === 'save') {
            $submittedKeys = is_array($_POST['key'] ?? null) ? $_POST['key'] : array();
            $submittedValues = is_array($_POST['translation'] ?? null) ? $_POST['translation'] : array();
            foreach ($submittedKeys as $rowId => $key) {
                if (array_key_exists($key, $translations) && array_key_exists($rowId, $submittedValues)) {
                    $translations[$key] = (string) $submittedValues[$rowId];
                }
            }

            if (language_editor_save($sellang, $translations, $errorMessage)) {
                $notice = count($submittedKeys) . ' ' . text('translations_saved_ok');
            }
        } elseif ($action === 'delete') {
            $removeKeys = is_array($_POST['remove'] ?? null) ? $_POST['remove'] : array();
            $removed = 0;
            foreach ($removeKeys as $key) {
                if (array_key_exists($key, $translations)) {
                    unset($translations[$key]);
                    $removed++;
                }
            }

            if ($removed === 0) {
                $errorMessage = 'Select at least one translation to delete.';
            } elseif (language_editor_save($sellang, $translations, $errorMessage)) {
                $notice = $removed . ' ' . text('labels_deleted');
            }
        } elseif ($action === 'add') {
            $newLabel = trim((string) ($_POST['newlabel'] ?? ''));
            if ($newLabel === '' || strlen($newLabel) > 128 || !preg_match('/^[A-Za-z0-9_.-]+$/', $newLabel)) {
                $errorMessage = 'Use 1–128 letters, numbers, dots, underscores, or hyphens for the label.';
            } elseif (array_key_exists($newLabel, $translations)) {
                $errorMessage = 'That translation label already exists.';
            } else {
                $translations[$newLabel] = $newLabel;
                if (language_editor_save($sellang, $translations, $errorMessage)) {
                    $notice = text('add_new_label') . ': ' . $newLabel;
                }
            }
        }
    }
}

