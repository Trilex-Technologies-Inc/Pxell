function language_editor_load($language)
{
    global $base_dir;

    $strings = array();
    $files = array(
        $base_dir . 'languages/lang_en.php',
        $base_dir . 'languages/global_en.php',
    );

    if ($language !== 'en') {
        $files[] = $base_dir . 'languages/lang_' . $language . '.php';
        $files[] = $base_dir . 'languages/global_' . $language . '.php';
    }

    foreach ($files as $file) {
        if (is_file($file) && is_readable($file)) {
            include $file;
        }
    }

    return is_array($strings) ? $strings : array();
}

function language_editor_save($language, $translations, &$saveError)
{
    global $base_dir;

    $languageDirectory = $base_dir . 'languages';
    $destination = $languageDirectory . '/global_' . $language . '.php';
    $temporary = tempnam($languageDirectory, '.language-');

    if ($temporary === false) {
        $saveError = 'Unable to create a temporary language file.';
        return false;
    }

    $content = "<?php\n\n/* Auto-generated by administration/edit_language.php. */\n\n";
    foreach ($translations as $key => $value) {
        $content .= '$strings[' . var_export((string) $key, true) . '] = ' . var_export((string) $value, true) . ";\n";
    }

    if (file_put_contents($temporary, $content, LOCK_EX) === false) {
        @unlink($temporary);
        $saveError = 'Unable to write the temporary language file.';
        return false;
    }

    if (!@rename($temporary, $destination)) {
        @unlink($temporary);
        $saveError = 'Unable to replace the language file. Check directory permissions.';
        return false;
    }

    return true;
}

